#!/usr/bin/env python3
"""A4 toy 1: postselected (normalised) RB with a Markovian but lossy map.

Checks the statements of A4-nonmarkov-theory.md section 2 on one qutrit:

 (a) the single-qutrit Clifford group (216 elements mod phase, generated by
     the Fourier gate H and the phase gate S = diag(1, 1, w)) is a unitary
     2-design (frame potential = 2);
 (b) fixed trace-decreasing map E, no twirl:
        r(m) = tr[O E^m(rho)] / tr[E^m(rho)]
     is a ratio of two sums of exponentials; its depth-windowed rate drifts;
     its large-m rate is lambda_O / lambda_1 (Perron eigenvalue of E);
 (c) twirled map E_tw = a Id + b Dep:  r(m) = (a / (a + b))^m exactly;
 (d) random-Clifford RB with E after every gate:
        ratio of sequence averages  E[N]/E[D] = (a/(a+b))^m  exactly,
        mean of per-sequence ratios E[N/D]   = (a/s)^m exactly iff
        E^dag(I) = s I (state-independent acceptance), and deviates from a
        single exponential otherwise.
All computations are exact linear algebra except (d), which is Monte Carlo
over random sequences (seeded).  Runtime: ~1 minute on one core.

    module load python/3.11
    python docs/correction-decoders/qutrit-512/notes/scripts/A4_lossy_markov.py
"""
from __future__ import annotations

import numpy as np

d = 3
w = np.exp(2j * np.pi / 3)
Xg = np.roll(np.eye(d), 1, axis=0)              # X|j> = |j+1>
Zg = np.diag([w ** j for j in range(d)])
Hg = np.array([[w ** (j * k) for k in range(d)] for j in range(d)]) / np.sqrt(d)
Sg = np.diag([1, 1, w])                          # S X S^dag = X Z (checked)
rng = np.random.default_rng(20261028)


def canon(U: np.ndarray) -> tuple:
    flat = U.ravel()
    k = int(np.flatnonzero(np.abs(flat) > 1e-9)[0])
    V = U * np.conj(flat[k]) / abs(flat[k])
    return tuple(np.round(V.ravel(), 6).tolist())


def clifford_group() -> list[np.ndarray]:
    group = {canon(np.eye(d)): np.eye(d, dtype=complex)}
    frontier = [np.eye(d, dtype=complex)]
    while frontier:
        new = []
        for U in frontier:
            for G in (Hg, Sg):
                V = G @ U
                key = canon(V)
                if key not in group:
                    group[key] = V
                    new.append(V)
        frontier = new
    return list(group.values())


def sup(U: np.ndarray) -> np.ndarray:
    """Row-major superoperator: vec(U r U^dag) = kron(U, conj U) vec(r)."""
    return np.kron(U, U.conj())


def kraus_sup(K: list[np.ndarray]) -> np.ndarray:
    return sum(np.kron(k, k.conj()) for k in K)


def random_cptp(n_kraus: int, strength: float) -> list[np.ndarray]:
    """Random CPTP map close to identity (error strength ~ strength)."""
    G = rng.normal(size=(n_kraus * d, d)) + 1j * rng.normal(size=(n_kraus * d, d))
    Q, _ = np.linalg.qr(G)                       # isometry (n_kraus*d x d)
    K = [Q[i * d:(i + 1) * d, :] for i in range(n_kraus)]
    # mix with identity: sqrt(1-strength) I plus sqrt(strength) random channel
    return [np.sqrt(1 - strength) * np.eye(d)] + [np.sqrt(strength) * k for k in K]


def sqrtm_psd(M: np.ndarray) -> np.ndarray:
    ev, U = np.linalg.eigh(M)
    return U @ np.diag(np.sqrt(np.clip(ev, 0, None))) @ U.conj().T


def lossy(K: list[np.ndarray], M: np.ndarray) -> list[np.ndarray]:
    """E(r) = Phi(sqrt(M) r sqrt(M)); E^dag(I) = M (acceptance operator)."""
    sM = sqrtm_psd(M)
    return [k @ sM for k in K]


def vec(r: np.ndarray) -> np.ndarray:
    return r.reshape(-1)


def tr_with(O: np.ndarray, v: np.ndarray) -> complex:
    return complex(np.trace(O @ v.reshape(d, d)))


def windowed_rates(r: np.ndarray, ms: np.ndarray) -> np.ndarray:
    return (r[1:] / r[:-1]) ** (1.0 / np.diff(ms))


def twirl(Esup: np.ndarray, group_sups: list[np.ndarray]) -> np.ndarray:
    return sum(Gs.conj().T @ Esup @ Gs for Gs in group_sups) / len(group_sups)


def main() -> None:
    group = clifford_group()
    print(f"(a) |Clifford group mod phase| = {len(group)}")
    assert np.allclose(Sg @ Xg @ Sg.conj().T, Xg @ Zg)
    fp = np.mean([[abs(np.trace(U.conj().T @ V)) ** 4 for V in group]
                  for U in group])
    print(f"    frame potential (2-design iff 2): {fp:.12f}")
    gs = [sup(U) for U in group]

    plus = np.ones((d, d), dtype=complex) / d         # |+><+|, X|+> = |+>
    O = Xg.conj().T                                   # tr[X^dag r]: 1 on |+>
    ms = np.arange(0, 41)

    # ---- (b) fixed lossy map, state-dependent acceptance ---------------
    K = random_cptp(2, 0.06)
    M = np.diag([1.0, 0.9, 0.75])                       # acceptance POVM
    E = kraus_sup(lossy(K, M))
    num = np.array([tr_with(O, np.linalg.matrix_power(E, m) @ vec(plus))
                    for m in ms])
    den = np.array([tr_with(np.eye(d), np.linalg.matrix_power(E, m)
                            @ vec(plus)) for m in ms]).real
    r = np.abs(num / den)
    lam = np.linalg.eigvals(E)
    lam = lam[np.argsort(-np.abs(lam))]
    rates = windowed_rates(r, ms)
    print("(b) fixed lossy map, no twirl")
    print(f"    |eigenvalues| of E: {np.round(np.abs(lam), 5)}")
    print(f"    windowed rate m=0->1: {rates[0]:.6f}, m=10->11: "
          f"{rates[10]:.6f}, m=39->40: {rates[-1]:.6f}")
    print(f"    r(40) = {r[-1]:.6f} (a non-zero limit means the Perron "
          f"eigenvector overlaps O: quasi-stationary state)")
    big = [200, 400]
    rb = [abs(tr_with(O, np.linalg.matrix_power(E, m) @ vec(plus)) /
              tr_with(np.eye(d), np.linalg.matrix_power(E, m) @ vec(plus)))
          for m in big]
    ev, R_ = np.linalg.eig(E)
    k1 = int(np.argmax(np.abs(ev)))
    Lft = np.linalg.inv(R_)
    pred = abs(tr_with(O, R_[:, k1]) * (Lft[k1] @ vec(plus)) /
               (tr_with(np.eye(d), R_[:, k1]) * (Lft[k1] @ vec(plus))))
    print(f"    r(200) = {rb[0]:.6f}, r(400) = {rb[1]:.6f}; Perron-vector "
          f"prediction tr[O v1]/tr[v1] = {pred:.6f}")

    # ---- (c) twirled map: exactly single exponential --------------------
    Etw = twirl(E, gs)
    # Etw = a Id + b Dep, Dep(r) = tr(r) I/d
    Id = np.eye(d * d)
    Dep = np.outer(vec(np.eye(d) / d), vec(np.eye(d)).conj())
    A_ = np.stack([Id.ravel(), Dep.ravel()], axis=1)
    coef, *_ = np.linalg.lstsq(A_, Etw.ravel(), rcond=None)
    a, b = coef.real
    resid = np.abs(A_ @ coef - Etw.ravel()).max()
    num_t = np.array([tr_with(O, np.linalg.matrix_power(Etw, m) @ vec(plus))
                      for m in ms])
    den_t = np.array([tr_with(np.eye(d), np.linalg.matrix_power(Etw, m)
                              @ vec(plus)) for m in ms]).real
    r_t = np.abs(num_t / den_t)
    err = np.max(np.abs(r_t - (a / (a + b)) ** ms))
    print("(c) twirled lossy map")
    print(f"    E_tw = a Id + b Dep with a={a:.6f}, b={b:.6f} "
          f"(fit residual {resid:.1e}); tr E_tw(r) = (a+b) tr r for all r")
    print(f"    max_m |r(m) - (a/(a+b))^m| = {err:.2e}")

    # ---- (d) random-Clifford RB, per-sequence normalisation -------------
    n_seq, m_max = 40000, 30
    nG = len(group)
    keys = {canon(U): i for i, U in enumerate(group)}
    mult = np.zeros((nG, nG), dtype=np.int64)        # index of G_i G_j
    for i, Ui in enumerate(group):
        for j, Uj in enumerate(group):
            mult[i, j] = keys[canon(Ui @ Uj)]
    inv = np.array([keys[canon(U.conj().T)] for U in group])
    gsup = np.stack(gs)                               # (nG, 9, 9)

    def run(Esup: np.ndarray, label: str) -> None:
        tw = twirl(Esup, gs)
        c, *_ = np.linalg.lstsq(A_, tw.ravel(), rcond=None)
        at, bt = c.real
        Mop = (Esup.conj().T @ vec(np.eye(d))).reshape(d, d)  # E^dag(I)
        state = np.tile(vec(plus), (n_seq, 1))
        prod = np.zeros(n_seq, dtype=np.int64)        # index of identity
        prod[:] = keys[canon(np.eye(d))]
        Nbar, Dbar, ratio_mean, ratio_se, abs_mean = [], [], [], [], []
        for m in range(1, m_max + 1):
            idx = rng.integers(0, nG, size=n_seq)
            state = np.einsum("nij,nj->ni", gsup[idx], state)
            state = state @ Esup.T
            prod = mult[idx, prod]
            fin = np.einsum("nij,nj->ni", gsup[inv[prod]], state)
            rho = fin.reshape(n_seq, d, d)
            N = np.einsum("ij,nji->n", O, rho)          # complex tr[O r]
            D = np.einsum("nii->n", rho).real
            Nbar.append(abs(N.mean())), Dbar.append(D.mean())
            ratio_mean.append(abs((N / D).mean()))
            ratio_se.append((N / D).real.std() / np.sqrt(n_seq))
            abs_mean.append(np.abs(N / D).mean())       # experiment-like
            ess = D.sum() ** 2 / np.sum(D ** 2)
        mm = np.arange(1, m_max + 1)
        Nbar, Dbar = np.array(Nbar), np.array(Dbar)
        ratio_mean, ratio_se = np.array(ratio_mean), np.array(ratio_se)
        f_ratio_avg = at / (at + bt)
        s_avg = np.trace(Mop).real / d
        # exact ratio of sequence averages from the twirl (no sampling)
        exact_N = np.array([tr_with(O, np.linalg.matrix_power(tw, m)
                                    @ vec(plus)) for m in mm])
        exact_D = np.array([tr_with(np.eye(d), np.linalg.matrix_power(tw, m)
                                    @ vec(plus)) for m in mm]).real
        print(f"(d) {label}: E^dag(I) eigenvalues "
              f"{np.round(np.linalg.eigvalsh((Mop + Mop.conj().T) / 2), 4)}"
              f", a+b = tr E^dag(I)/d = {s_avg:.6f}")
        print(f"    exact ratio of averages E[N]/E[D] vs (a/(a+b))^m: max rel"
              f" dev {np.max(np.abs(np.abs(exact_N / exact_D) / f_ratio_avg ** mm - 1)):.1e}")
        print(f"    Monte Carlo ratio of averages: max rel dev "
              f"{np.max(np.abs(Nbar / Dbar / f_ratio_avg ** mm - 1)):.2e}; "
              f"effective sample size of D at m={m_max}: {ess:.0f} of {n_seq}")
        # single exponential fit to the mean of ratios (weighted, log-linear)
        wts = (ratio_mean / ratio_se) ** 2
        Am = np.stack([np.ones_like(mm, dtype=float), mm], axis=1)
        W = np.diag(wts)
        beta = np.linalg.solve(Am.T @ W @ Am, Am.T @ W @ np.log(ratio_mean))
        fit = np.exp(Am @ beta)
        chi2 = np.sum(((ratio_mean - fit) / ratio_se) ** 2)
        print(f"    mean of ratios: single-exp fit f={np.exp(beta[1]):.6f}"
              f" vs a/(a+b)={f_ratio_avg:.6f}; chi2/dof = "
              f"{chi2 / (m_max - 2):.2f}; mean-of-ratios minus "
              f"(a/(a+b))^m at m={m_max}: "
              f"{ratio_mean[-1] - f_ratio_avg ** m_max:+.2e} "
              f"(se {ratio_se[-1]:.1e})")
        print(f"    experiment-like mean|N/D| minus |mean N/D| at m={m_max}: "
              f"{abs_mean[-1] - ratio_mean[-1]:+.1e} (phase-noise bias; zero "
              f"for the real, Pauli-symmetric LRB-D statistic)")

    K2 = random_cptp(2, 0.04)
    run(kraus_sup(lossy(K2, 0.8 * np.eye(d))), "acceptance independent of state")
    run(kraus_sup(lossy(K2, np.diag([1.0, 0.55, 0.25]))),
        "acceptance depends on state")


if __name__ == "__main__":
    main()
