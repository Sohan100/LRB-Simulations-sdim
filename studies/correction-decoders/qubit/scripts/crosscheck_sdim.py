#!/usr/bin/env python
"""Work package A: cross-check the ``lrb_qubit`` Stim model against the repo's sdim pipeline at d = 2.

The qubit ``[[5,1,2]]`` model in ``src/lrb_qubit`` was written directly in
Stim. This script rebuilds the same LRB circuits with the repository's own
qudit pipeline, run at local dimension d = 2, and compares the two.

1. ``FoldedQubitCode`` is a qubit ``LRBCodeDefinition`` written with sdim's
   d = 2 gate names (H, P, P_INV, CNOT, CZ, SWAP, X, Z, I, M, RESET). It
   mirrors the ``folded_qutrit`` profile of
   ``src/lrb/code_simulation_profiles.py``: z_ALT Z checks, X checks, the
   ancilla reset block, the data-0/3 terminal readout and the ``const=0``
   direct X readout of all five data qubits. At d = 2, H_INV = H,
   CNOT_INV = CNOT, CZ_INV = CZ, X_INV = X and Z_INV = Z. sdim's P is
   S = diag(1, i), P_INV is S^dagger, and ``add_gate("CNOT", a, b)`` has
   control a and target b (all checked by ``selftest``).
2. Circuits are generated by ``LRBCircuitGenerator(noise_model="si1000")``
   for the same Clifford descriptors as the Stim model: the first sequences
   of the lead's grid (``lrb_qubit.experiment.clifford_sequences``, seed
   20261028). Descriptors use P for S, exactly as in the qutrit catalog.
3. sdim's Pauli-frame simulator samples them. ``sdim_frame_sample`` makes the
   same internal calls as ``Program.simulate`` (and as the repo's DEM
   backend) but skips building one Python object per shot; ``selftest``
   checks that it reproduces ``Program.simulate`` bit for bit under fixed
   seeds. The repo's own unpackers, ``postselect_*`` functions and
   ``extract_lrb_counts`` turn the output into decisions and logical counts,
   and the noiseless reference shot is dropped as ``LRBSimulationPipeline.LRB``
   does.
4. The Stim model (``build_lrb_circuit(terminal="data2")`` and
   ``build_lrb_const0_circuit``) is sampled on identical sequences. Rejection
   (``const=1``, ``unif=1``, ``const=0``), logical flip rates among accepted
   shots, per-detector marginals (raw ancilla flips and difference detection
   events) and joint syndrome histograms are compared with two-proportion
   z-tests and chi-square homogeneity tests, with Holm-Bonferroni and
   Benjamini-Hochberg corrections.
5. ``dem`` translates every generated sdim circuit gate by gate into Stim and
   checks that its detector error model over raw ancilla-flip detectors is
   identical to the lead circuit's. This is an exact test with no sampling
   noise.

Usage (from the repository root)::

    module load python/3.11
    export OPENBLAS_NUM_THREADS=1 OMP_NUM_THREADS=1 MKL_NUM_THREADS=1
    export PYTHONPATH=$PWD/src
    python studies/correction-decoders/qubit/scripts/crosscheck_sdim.py selftest   # d = 2 semantics
    python studies/correction-decoders/qubit/scripts/crosscheck_sdim.py dem        # exact DEM identity
    python studies/correction-decoders/qubit/scripts/crosscheck_sdim.py sample --workers 4
    python studies/correction-decoders/qubit/scripts/crosscheck_sdim.py analyze    # two-sample tests
    python studies/correction-decoders/qubit/scripts/crosscheck_sdim.py confirm    # fresh-seed follow-up
    python studies/correction-decoders/qubit/scripts/crosscheck_sdim.py recheck    # deep-circuit recheck
    python studies/correction-decoders/qubit/scripts/crosscheck_sdim.py table      # markdown tables

Heavy steps (``sample``, ``confirm``, ``recheck``) belong on the shared
allocation; the exact commands and shot counts used are in
``studies/correction-decoders/qubit/notes/A-sdim-crosscheck.md``.
Outputs go to ``studies/correction-decoders/qubit/results/A/``.
"""

