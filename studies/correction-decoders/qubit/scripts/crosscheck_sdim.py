def task_seed(*parts: int) -> int:
    return int(np.random.SeedSequence([7151, *parts]).generate_state(1)[0])


def run_task(task: tuple) -> tuple:
    (sim, kind, seq_index, depth, p_index, chunk, shots, seed) = task
    sequence = sequences()[seq_index]
    p = PROBS[p_index]
    lc = lead_circuit(kind, sequence, depth, p)
    start = time.perf_counter()
    if sim == "sdim":
        circuit = sdim_circuits(sequence, [depth], p, kind)[depth]
        output, frame = sdim_frame_sample(circuit, shots, seed)
        data = process_sdim(kind, output, frame, depth, shots, lc)
        refs_ok = (all(v == 0 for v in data["ref_values"])
                   and data["logical_ref"] == 0)
        if not refs_ok:
            raise RuntimeError(f"Non-zero sdim reference values in {task}.")
    else:
        data = stim_chunk(kind, lc, depth, shots, seed)
    summary = summarize(kind, data)
    summary["seconds"] = time.perf_counter() - start
    return task, summary


def build_tasks(sdim_shots: int, stim_shots: int, chunk: int,
                deep_sdim_shots: int, deep_stim_shots: int) -> list[tuple]:
    tasks = []
    circuits = [(kind, s, d, pi) for kind in ("lrb", "const0")
                for s in range(NUM_SEQ) for d in DEPTHS
                for pi in range(len(PROBS))]
    deep = [(kind, DEEP[0], DEEP[1], pi) for kind in ("lrb", "const0")
            for pi in range(len(PROBS))]
    for group, n_sdim, n_stim in ((circuits, sdim_shots, stim_shots),
                                  (deep, deep_sdim_shots, deep_stim_shots)):
        for kind, s, d, pi in group:
            kind_id = 0 if kind == "lrb" else 1
            if n_sdim > 0:
                size = chunk if d <= 6 else max(chunk // 2, 1)
                n_chunks = math.ceil(n_sdim / size)
                for c in range(n_chunks):
                    shots = min(size, n_sdim - c * size)
                    tasks.append(("sdim", kind, s, d, pi, c, shots,
                                  task_seed(0, kind_id, s, d, pi, c)))
            if n_stim > 0:
                size = 500_000
                for c in range(math.ceil(n_stim / size)):
                    shots = min(size, n_stim - c * size)
                    tasks.append(("stim", kind, s, d, pi, c, shots,
                                  task_seed(1, kind_id, s, d, pi, c)))
    # Longest tasks first for better load balance.
    tasks.sort(key=lambda t: (t[0] != "sdim", -t[3], -t[6]))
    return tasks


def detector_names(kind: str, depth: int) -> list[tuple[int, int]]:
    if kind == "lrb":
        return [(r, s) for r in range(depth + 1) for s in range(4)]
    return [(0, 0), (0, 1)]


def write_counts(totals: dict, path_counts: Path, path_hist: Path) -> None:
    rows = []
    hist_rows = []
    keys = sorted({key[1:] for key in totals})
    for kind, s, d, pi in keys:
        a = totals.get(("sdim", kind, s, d, pi))
        b = totals.get(("stim", kind, s, d, pi))
        if a is None or b is None:
            continue
        p = PROBS[pi]
        base = {"kind": kind, "seq": s, "depth": d, "p": p}
        policies = ("const1", "unif1") if kind == "lrb" else ("const0",)
        quantities = []
        for name in policies:
            quantities.append((f"rej_{name}", a[f"rej_{name}"], a["n"],
                               b[f"rej_{name}"], b["n"]))
            quantities.append((f"flip_{name}|acc", a[f"flip_{name}"],
                               a[f"acc_{name}"], b[f"flip_{name}"],
                               b[f"acc_{name}"]))
        quantities.append(("flip_all", a["flip_all"], a["n"], b["flip_all"],
                           b["n"]))
        for kind_name in ("raw", "diff"):
            if kind == "const0" and kind_name == "diff":
                continue
            for r, st in detector_names(kind, d):
                label = (f"{kind_name}_r{r}_s{st}" if kind == "lrb"
                         else f"xstab_{st}")
                quantities.append((label, int(a[kind_name][r, st]), a["n"],
                                   int(b[kind_name][r, st]), b["n"]))
        for q, ka, na, kb, nb in quantities:
            rows.append({**base, "quantity": q, "sdim_k": int(ka),
                         "sdim_n": int(na), "stim_k": int(kb),
                         "stim_n": int(nb)})
        for table in ("hist_term", "hist_weight"):
            for bin_index, (ca, cb) in enumerate(zip(a[table], b[table])):
                if ca or cb:
                    hist_rows.append({**base, "table": table,
                                      "bin": bin_index, "sdim": int(ca),
                                      "stim": int(cb)})
    write_csv(path_counts, rows)
    write_csv(path_hist, hist_rows)


def write_csv(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        path.write_text("")
        return
    def fmt(value):
        if isinstance(value, (float, np.floating)):
            return "nan" if math.isnan(value) else f"{float(value):.7g}"
        return value

    with open(path, "w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows([{k: fmt(v) for k, v in row.items()}
                          for row in rows])


def read_csv(path: Path) -> list[dict]:
    with open(path, newline="") as handle:
        return list(csv.DictReader(handle))


def cmd_sample(args) -> None:
    tasks = build_tasks(args.sdim_shots, args.stim_shots, args.chunk,
                        args.deep_sdim_shots, args.deep_stim_shots)
    print(f"{len(tasks)} tasks on {args.workers} workers", flush=True)
    totals: dict = {}
    seconds: dict = {}
    start = time.perf_counter()
    with ProcessPoolExecutor(max_workers=args.workers) as pool:
        for i, (task, summary) in enumerate(pool.map(run_task, tasks,
                                                     chunksize=1)):
            key = task[:5]
            seconds[key] = seconds.get(key, 0.0) + summary.pop("seconds")
            totals[key] = add_counts(totals.get(key), summary)
            if (i + 1) % 20 == 0 or i + 1 == len(tasks):
                print(f"  {i + 1}/{len(tasks)} tasks, "
                      f"{time.perf_counter() - start:.0f}s", flush=True)
    out = Path(args.out)
    write_counts(totals, out / "counts.csv", out / "hist.csv")
    meta = [
        {"key": "seq_seed", "value": SEQ_SEED},
        {"key": "sequences", "value": " | ".join(
            " ".join(s[:max(DEPTHS + (DEEP[1],))]) for s in sequences())},
        {"key": "depths", "value": " ".join(map(str, DEPTHS))},
        {"key": "deep_circuit", "value": f"seq {DEEP[0]} depth {DEEP[1]}"},
        {"key": "probs", "value": " ".join(map(str, PROBS))},
        {"key": "sdim_shots", "value": args.sdim_shots},
        {"key": "stim_shots", "value": args.stim_shots},
        {"key": "deep_sdim_shots", "value": args.deep_sdim_shots},
        {"key": "deep_stim_shots", "value": args.deep_stim_shots},
        {"key": "chunk", "value": args.chunk},
        {"key": "workers", "value": args.workers},
        {"key": "wall_seconds", "value": round(time.perf_counter() - start)},
        {"key": "sdim_cpu_seconds", "value": round(sum(
            v for k, v in seconds.items() if k[0] == "sdim"))},
        {"key": "stim_cpu_seconds", "value": round(sum(
            v for k, v in seconds.items() if k[0] == "stim"))},
        {"key": "stim_version", "value": stim.__version__},
        {"key": "numpy_version", "value": np.__version__},
    ]
    write_csv(out / "sample_meta.csv", meta)
    print(f"wrote {out / 'counts.csv'} and {out / 'hist.csv'}")


