def _apply_physical_qubit_gate(circuit: Circuit, gate: str) -> None:
    """Physical-RB gate mapper (unused by LRB; kept for a complete definition)."""
    circuit.add_gate(QUTRIT_TO_QUBIT_NAME.get(gate, gate), 0)


