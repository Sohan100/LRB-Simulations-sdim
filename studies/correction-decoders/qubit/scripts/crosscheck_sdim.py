# The two largest sdim-vs-exact marginal deviations of the main run
# (|z| = 4.21 and 3.71), fixed here before resampling them with fresh seeds.
CONFIRM_TARGETS = (("lrb", 0, 22, 0.005, "diff_r19_s0"),
                   ("const0", 1, 6, 0.005, "xstab_0"))


def cmd_confirm(args) -> None:
    tasks = []
    for kind, s, d, p, _ in CONFIRM_TARGETS:
        kind_id = 0 if kind == "lrb" else 1
        pi = PROBS.index(p)
        size = args.chunk if d <= 6 else max(args.chunk // 2, 1)
        for c in range(math.ceil(args.confirm_shots / size)):
            shots = min(size, args.confirm_shots - c * size)
            # Seed namespace 2: independent of the main run (0 and 1).
            tasks.append(("sdim", kind, s, d, pi, c, shots,
                          task_seed(2, kind_id, s, d, pi, c)))
    print(f"{len(tasks)} confirmation tasks on {args.workers} workers",
          flush=True)
    totals: dict = {}
    with ProcessPoolExecutor(max_workers=args.workers) as pool:
        for task, summary in pool.map(run_task, tasks, chunksize=1):
            summary.pop("seconds")
            totals[task[:5]] = add_counts(totals.get(task[:5]), summary)
    rows = []
    for kind, s, d, p, quantity in CONFIRM_TARGETS:
        total = totals[("sdim", kind, s, d, PROBS.index(p))]
        exact = exact_marginals(kind, sequences()[s], d, p)
        # All marginals of the circuit, for context.
        zs = []
        target = None
        for name, value in exact.items():
            if name == "flip_all":
                k = total["flip_all"]
            elif name.startswith("xstab_"):
                k = int(total["raw"][0, int(name[-1])])
            else:
                kind_name, rest = name.split("_", 1)
                r, st = (int(x[1:]) for x in rest.split("_"))
                k = int(total[kind_name][r, st])
            n = total["n"]
            se = math.sqrt(value * (1 - value) / n)
            z = (k / n - value) / se if se > 0 else 0.0
            zs.append(z)
            if name == quantity:
                target = (k, n, value, z)
        k, n, value, z = target
        p_value = 2 * stats.norm.sf(abs(z))
        zs = np.array(zs)
        rows.append({
            "kind": kind, "seq": s, "depth": d, "p": p, "quantity": quantity,
            "exact": value, "sdim_k": k, "sdim_n": n, "rate_sdim": k / n,
            "se_sdim": math.sqrt(value * (1 - value) / n),
            "z_vs_exact": z, "p_value": p_value,
            "p_bonferroni": min(1.0, len(CONFIRM_TARGETS) * p_value),
            "circuit_marginals": len(zs),
            "circuit_max_abs_z": float(np.abs(zs).max()),
            "circuit_ks_p": float(stats.kstest(zs, "norm").pvalue),
        })
        print(f"{kind} seq {s} m={d} p={p} {quantity}: exact {value:.5f}, "
              f"sdim {k / n:.5f} (n={n}), z={z:+.2f}, p={p_value:.3f}, "
              f"Bonferroni p={rows[-1]['p_bonferroni']:.3f}; all {len(zs)} "
              f"marginals of the circuit: max|z|={np.abs(zs).max():.2f}, "
              f"KS p={rows[-1]['circuit_ks_p']:.3f}")
    write_csv(Path(args.out) / "confirm.csv", rows)


RECHECK_CIRCUIT = ("lrb", 0, 22, 0.005)


def _marginal_z(total: dict, exact: dict) -> dict[str, tuple]:
    """{name: (k, n, z vs exact)} for every marginal of one circuit."""
    out = {}
    n = total["n"]
    for name, value in exact.items():
        if name == "flip_all":
            k = total["flip_all"]
        elif name.startswith("xstab_"):
            k = int(total["raw"][0, int(name[-1])])
        else:
            kind_name, rest = name.split("_", 1)
            r, st = (int(x[1:]) for x in rest.split("_"))
            k = int(total[kind_name][r, st])
        se = math.sqrt(value * (1 - value) / n)
        out[name] = (k, n, (k / n - value) / se if se > 0 else 0.0)
    return out


def cmd_recheck(args) -> None:
    """All marginals of the deep circuit: fresh sdim run + Stim null for max|z|.

    The null distribution of max|z| over the circuit's correlated marginals
    is estimated from independent Stim replicates of the same size.
    """
    kind, s, d, p = RECHECK_CIRCUIT
    kind_id, pi = 0 if kind == "lrb" else 1, PROBS.index(p)
    size = max(args.chunk // 2, 1)
    tasks = []
    for c in range(math.ceil(args.recheck_shots / size)):
        shots = min(size, args.recheck_shots - c * size)
        tasks.append(("sdim", kind, s, d, pi, c, shots,
                      task_seed(3, kind_id, s, d, pi, c)))
    for rep in range(args.null_replicates):
        # Stim replicate ``rep`` = one task of recheck_shots shots.
        tasks.append(("stim", kind, s, d, pi, rep, args.recheck_shots,
                      task_seed(4, kind_id, s, d, pi, rep)))
    print(f"{len(tasks)} recheck tasks on {args.workers} workers", flush=True)
    sdim_total = None
    stim_reps: dict = {}
    with ProcessPoolExecutor(max_workers=args.workers) as pool:
        for task, summary in pool.map(run_task, tasks, chunksize=1):
            summary.pop("seconds")
            if task[0] == "sdim":
                sdim_total = add_counts(sdim_total, summary)
            else:
                stim_reps[task[5]] = summary
    exact = exact_marginals(kind, sequences()[s], d, p)
    sdim_z = _marginal_z(sdim_total, exact)
    names = list(exact)
    z = np.array([sdim_z[nm][2] for nm in names])
    p_values = 2 * stats.norm.sf(np.abs(z))
    adjusted = holm(p_values)
    null_max = np.array([
        max(abs(v[2]) for v in _marginal_z(rep, exact).values())
        for rep in stim_reps.values()])
    observed = float(np.abs(z).max())
    p_null = (1 + int((null_max >= observed).sum())) / (1 + len(null_max))
    rows = [{"kind": kind, "seq": s, "depth": d, "p": p, "quantity": nm,
             "exact": exact[nm], "sdim_k": sdim_z[nm][0],
             "sdim_n": sdim_z[nm][1], "rate_sdim": sdim_z[nm][0]
             / sdim_z[nm][1], "z_vs_exact": zz, "p_value": pv,
             "p_holm": ph} for nm, zz, pv, ph in zip(names, z, p_values,
                                                       adjusted)]
    write_csv(Path(args.out) / "recheck_marginals.csv", rows)
    summary = [{
        "kind": kind, "seq": s, "depth": d, "p": p,
        "sdim_shots": int(sdim_total["n"]), "marginals": len(names),
        "max_abs_z": observed, "argmax": names[int(np.abs(z).argmax())],
        "min_p_holm": float(np.nanmin(adjusted)),
        "ks_p": float(stats.kstest(z, "norm").pvalue),
        "mean_z": float(z.mean()), "sd_z": float(z.std(ddof=1)),
        "stim_null_replicates": len(null_max),
        "stim_null_max_abs_z_median": float(np.median(null_max)),
        "stim_null_max_abs_z_95pct": float(np.quantile(null_max, 0.95)),
        "p_max_abs_z_vs_stim_null": p_null,
    }]
    write_csv(Path(args.out) / "recheck_summary.csv", summary)
    for key, value in summary[0].items():
        print(f"  {key}: {value}")


