def two_proportion(k1: int, n1: int, k2: int, n2: int) -> dict:
    """Pooled two-sided two-proportion z-test (plus Fisher for small counts)."""
    if n1 == 0 or n2 == 0:
        return {"rate_sdim": math.nan, "rate_stim": math.nan,
                "se_sdim": math.nan, "se_stim": math.nan, "diff": math.nan,
                "se_diff": math.nan, "se_pooled": math.nan, "z": math.nan,
                "p_value": math.nan, "p_fisher": math.nan}
    r1, r2 = k1 / n1, k2 / n2
    pooled = (k1 + k2) / (n1 + n2)
    se0 = math.sqrt(pooled * (1 - pooled) * (1 / n1 + 1 / n2))
    z = (r1 - r2) / se0 if se0 > 0 else 0.0
    p_value = 2 * stats.norm.sf(abs(z)) if se0 > 0 else 1.0
    expected_min = min(pooled * n1, (1 - pooled) * n1, pooled * n2,
                       (1 - pooled) * n2)
    p_fisher = math.nan
    if expected_min < 10:
        p_fisher = float(stats.fisher_exact(
            [[k1, n1 - k1], [k2, n2 - k2]])[1])
    return {
        "rate_sdim": r1, "rate_stim": r2,
        "se_sdim": math.sqrt(r1 * (1 - r1) / n1),
        "se_stim": math.sqrt(r2 * (1 - r2) / n2),
        "diff": r1 - r2,
        "se_diff": math.sqrt(r1 * (1 - r1) / n1 + r2 * (1 - r2) / n2),
        "se_pooled": se0,
        "z": z, "p_value": p_value, "p_fisher": p_fisher,
    }


def holm(p_values: Sequence[float]) -> np.ndarray:
    """Holm-Bonferroni adjusted p-values (NaN entries stay NaN)."""
    p = np.asarray(p_values, dtype=float)
    adjusted = np.full_like(p, np.nan)
    valid = np.flatnonzero(~np.isnan(p))
    order = valid[np.argsort(p[valid])]
    m = len(order)
    running = 0.0
    for rank, index in enumerate(order):
        running = max(running, min(1.0, (m - rank) * p[index]))
        adjusted[index] = running
    return adjusted


def benjamini_hochberg(p_values: Sequence[float]) -> np.ndarray:
    p = np.asarray(p_values, dtype=float)
    adjusted = np.full_like(p, np.nan)
    valid = np.flatnonzero(~np.isnan(p))
    order = valid[np.argsort(p[valid])]
    m = len(order)
    running = 1.0
    for rank in range(m - 1, -1, -1):
        index = order[rank]
        running = min(running, p[index] * m / (rank + 1))
        adjusted[index] = running
    return adjusted


def chi_square_homogeneity(a: Sequence[int], b: Sequence[int]) -> dict:
    """2 x K Pearson test; sparse columns (expected < 5) are pooled."""
    a = np.asarray(a, dtype=float)
    b = np.asarray(b, dtype=float)
    na, nb = a.sum(), b.sum()
    col = a + b
    expected_min = np.minimum(col * na, col * nb) / (na + nb)
    keep = expected_min >= 5
    columns_a = list(a[keep])
    columns_b = list(b[keep])
    if (~keep).any() and col[~keep].sum() > 0:
        columns_a.append(a[~keep].sum())
        columns_b.append(b[~keep].sum())
    table = np.array([columns_a, columns_b])
    table = table[:, table.sum(axis=0) > 0]
    if table.shape[1] < 2:
        return {"chi2": 0.0, "dof": 0, "p_value": 1.0,
                "bins_used": int(table.shape[1])}
    chi2, p_value, dof, _ = stats.chi2_contingency(table, correction=False)
    return {"chi2": float(chi2), "dof": int(dof), "p_value": float(p_value),
            "bins_used": int(table.shape[1])}


HEADLINE = ("rej_const1", "rej_unif1", "flip_const1|acc", "flip_unif1|acc",
            "rej_const0", "flip_const0|acc")


def quantity_family(quantity: str) -> str:
    if quantity in HEADLINE:
        return "headline"
    return "marginal"


def quantity_type(row: dict) -> str:
    q = row["quantity"]
    if q.startswith("raw_"):
        return f"{row['kind']}:raw_detector"
    if q.startswith("diff_"):
        return f"{row['kind']}:diff_detector"
    if q.startswith("xstab_"):
        return "const0:xstab_detector"
    return f"{row['kind']}:{q}"


def cmd_analyze(args) -> None:
    out = Path(args.out)
    counts = read_csv(out / "counts.csv")
    hists = read_csv(out / "hist.csv")

    tests = []
    for row in counts:
        result = two_proportion(int(row["sdim_k"]), int(row["sdim_n"]),
                                int(row["stim_k"]), int(row["stim_n"]))
        tests.append({"kind": row["kind"], "seq": int(row["seq"]),
                      "depth": int(row["depth"]), "p": float(row["p"]),
                      "quantity": row["quantity"],
                      "family": quantity_family(row["quantity"]),
                      "type": quantity_type(row),
                      "sdim_k": int(row["sdim_k"]),
                      "sdim_n": int(row["sdim_n"]),
                      "stim_k": int(row["stim_k"]),
                      "stim_n": int(row["stim_n"]), **result})

    # Absolute reference: exact values from the lead's DEM (all marginals;
    # headline quantities where the joint distribution is tractable).
    exact_cache: dict = {}
    seqs = sequences()
    for t in tests:
        key = (t["family"], t["kind"], t["seq"], t["depth"], t["p"])
        if key not in exact_cache:
            fn = (exact_marginals if t["family"] == "marginal"
                  else exact_headline)
            exact_cache[key] = fn(t["kind"], seqs[t["seq"]], t["depth"],
                                  t["p"])
        exact = exact_cache[key].get(t["quantity"], math.nan)
        t["exact"] = exact
        if math.isnan(exact):
            t["z_sdim_vs_exact"] = t["z_stim_vs_exact"] = math.nan
            continue
        for sim in ("sdim", "stim"):
            n = t[f"{sim}_n"]
            if n == 0:
                t[f"z_{sim}_vs_exact"] = math.nan
                continue
            se = math.sqrt(exact * (1 - exact) / n)
            t[f"z_{sim}_vs_exact"] = ((t[f"rate_{sim}"] - exact) / se
                                      if se > 0 else 0.0)

    joint = []
    grouped: dict = {}
    for row in hists:
        key = (row["kind"], int(row["seq"]), int(row["depth"]),
               float(row["p"]), row["table"])
        grouped.setdefault(key, ([], [], []))
        grouped[key][0].append(int(row["sdim"]))
        grouped[key][1].append(int(row["stim"]))
        grouped[key][2].append(int(row["bin"]))
    for (kind, s, d, p, table), (a, b, _) in sorted(grouped.items()):
        result = chi_square_homogeneity(a, b)
        joint.append({"kind": kind, "seq": s, "depth": d, "p": p,
                      "table": table, "sdim_n": sum(a), "stim_n": sum(b),
                      **result, "family": "joint"})

    # Degenerate comparisons (no variance under the null: both samples all 0
    # or all 1, or no accepted shots; joint tables with a single bin) carry
    # no information and are left out of the corrections.
    for t in tests:
        t["informative"] = bool(not math.isnan(t["se_pooled"])
                                and t["se_pooled"] > 0)
    for t in joint:
        t["informative"] = bool(t["dof"] > 0)

    def corrected(rows, fn):
        return fn([t["p_value"] if t["informative"] else math.nan
                   for t in rows])

    # Multiple-comparison corrections: within each family and globally.
    for family in ("headline", "marginal"):
        rows = [t for t in tests if t["family"] == family]
        for name, fn in (("p_holm_family", holm),
                         ("p_bh_family", benjamini_hochberg)):
            for t, value in zip(rows, corrected(rows, fn)):
                t[name] = value
    for name, fn in (("p_holm_family", holm),
                     ("p_bh_family", benjamini_hochberg)):
        for t, value in zip(joint, corrected(joint, fn)):
            t[name] = value
    everything = tests + joint
    for name, fn in (("p_holm_global", holm),
                     ("p_bh_global", benjamini_hochberg)):
        for t, value in zip(everything, corrected(everything, fn)):
            t[name] = value

    # Combined evidence per quantity type across independent circuits.
    combined = []
    types = sorted({t["type"] for t in tests})
    for qtype in types:
        for p_label in ("all", *map(str, PROBS)):
            rows = [t for t in tests if t["type"] == qtype
                    and t["informative"]
                    and (p_label == "all" or t["p"] == float(p_label))]
            if not rows:
                continue
            # Several detectors of one circuit share shots, so combine one
            # z per circuit for detector types (mean z over detectors keeps
            # the sign of a common bias; its null variance is <= 1/len).
            per_circuit: dict = {}
            for t in rows:
                per_circuit.setdefault((t["seq"], t["depth"], t["p"]),
                                       []).append(t["z"])
            zs = np.array([np.mean(v) for v in per_circuit.values()])
            stouffer = zs.sum() / math.sqrt(len(zs))
            # Inverse-variance weights from the pooled (null) SE.
            usable = [t for t in rows if t["se_pooled"] > 0]
            weights = np.array([1 / t["se_pooled"] ** 2 for t in usable])
            diffs = np.array([t["diff"] for t in usable])
            rel = np.array([t["diff"] / t["rate_stim"] for t in usable
                            if t["rate_stim"] > 0])
            combined.append({
                "type": qtype, "p": p_label, "circuits": len(zs),
                "tests": len(rows),
                "stouffer_z": stouffer,
                "stouffer_p": 2 * stats.norm.sf(abs(stouffer)),
                "max_abs_z": float(np.max(np.abs([t["z"] for t in rows]))),
                "weighted_mean_diff": float((weights * diffs).sum()
                                            / weights.sum()),
                "weighted_mean_diff_se": float(1 / math.sqrt(weights.sum())),
                "median_rel_diff": float(np.median(rel)) if len(rel) else
                math.nan,
            })
    stouffer_adjusted = holm([c["stouffer_p"] for c in combined])
    for c, value in zip(combined, stouffer_adjusted):
        c["stouffer_p_holm"] = value

    write_csv(out / "tests_headline.csv",
              [t for t in tests if t["family"] == "headline"])
    write_csv(out / "tests_marginals.csv",
              [t for t in tests if t["family"] == "marginal"])
    write_csv(out / "tests_joint.csv", joint)
    write_csv(out / "tests_combined.csv", combined)

    # Console summary.
    def count_sig(rows, key, alpha=0.05):
        return sum(1 for r in rows if not math.isnan(r.get(key, math.nan))
                   and r[key] < alpha)

    print(f"individual tests: {len(tests)} proportions + {len(joint)} joint "
          f"({sum(t['informative'] for t in everything)} informative)")
    for family in ("headline", "marginal"):
        rows = [t for t in tests if t["family"] == family]
        zs = np.array([t["z"] for t in rows if t["informative"]])
        print(f"  {family:9s}: n={len(zs):4d} raw p<0.05: "
              f"{count_sig(rows, 'p_value'):3d}  Holm(family) sig: "
              f"{count_sig(rows, 'p_holm_family')}  BH(family) sig: "
              f"{count_sig(rows, 'p_bh_family')}  mean z {zs.mean():+.3f} "
              f"sd z {zs.std(ddof=1):.3f} max|z| {np.abs(zs).max():.2f}")
    informative_joint = [j for j in joint if j["informative"]]
    print(f"  joint    : n={len(informative_joint):4d} raw p<0.05: "
          f"{count_sig(informative_joint, 'p_value'):3d}  Holm(family) sig: "
          f"{count_sig(joint, 'p_holm_family')}  min p "
          f"{min(j['p_value'] for j in informative_joint):.3g}")
    # Goodness of fit of each simulator's terminal joint histogram
    # (last-round syndrome bits x logical bit) against the exact joint law.
    # One test per circuit and simulator, independent across circuits.
    gof = []
    for (kind, s, d, p, table), (a, b, bins) in sorted(grouped.items()):
        if table != "hist_term":
            continue
        lc = lead_circuit(kind, seqs[s], d, p)
        mechanisms = dem_mechanisms(
            lead_raw_circuit(kind, lc).detector_error_model())
        dets = ([4 * d + st for st in range(4)] if kind == "lrb"
                else [0, 1])
        expected_p = _exact_joint(mechanisms,
                                  [("d", x) for x in dets] + [("o", 0)])
        for sim, counts in (("sdim", a), ("stim", b)):
            observed = np.zeros(len(expected_p))
            observed[np.asarray(bins)] = counts
            n = observed.sum()
            expected = n * expected_p
            keep = expected >= 5
            obs_cells = list(observed[keep])
            exp_cells = list(expected[keep])
            if (~keep).any() and expected[~keep].sum() > 0:
                obs_cells.append(observed[~keep].sum())
                exp_cells.append(expected[~keep].sum())
            obs_cells, exp_cells = np.array(obs_cells), np.array(exp_cells)
            dof = len(obs_cells) - 1
            chi2 = float(((obs_cells - exp_cells) ** 2 / exp_cells).sum()
                         ) if dof > 0 else 0.0
            gof.append({"kind": kind, "seq": s, "depth": d, "p": p,
                        "sim": sim, "n": int(n), "cells": len(obs_cells),
                        "chi2": chi2, "dof": dof,
                        "p_value": float(stats.chi2.sf(chi2, dof))
                        if dof > 0 else 1.0})
    for sim in ("sdim", "stim"):
        rows = [g for g in gof if g["sim"] == sim and g["dof"] > 0]
        adjusted = holm([g["p_value"] for g in rows])
        for g, value in zip(rows, adjusted):
            g["p_holm"] = value
        total_chi2 = sum(g["chi2"] for g in rows)
        total_dof = sum(g["dof"] for g in rows)
        print(f"  {sim} terminal joint vs exact (GOF, {len(rows)} circuits):"
              f" sum chi2 {total_chi2:.1f} on {total_dof} dof, p="
              f"{stats.chi2.sf(total_chi2, total_dof):.3f}; min Holm p "
              f"{min(g['p_holm'] for g in rows):.3f}")
    for g in gof:
        g.setdefault("p_holm", math.nan)
    write_csv(out / "tests_gof_exact.csv", gof)

    exact_rows = []
    for family in ("headline", "marginal"):
        usable = [t for t in tests if t["family"] == family
                  and not math.isnan(t["exact"]) and 0 < t["exact"] < 1
                  and t["sdim_n"] > 0 and t["stim_n"] > 0]
