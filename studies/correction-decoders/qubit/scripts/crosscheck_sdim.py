# Qutrit gate name -> its d = 2 equivalent. At d = 2 every Pauli, H, CNOT and
# CZ is its own inverse; P and P_INV stay distinct (S and S^dagger).
QUTRIT_TO_QUBIT_NAME = {"H_INV": "H", "CNOT_INV": "CNOT", "CZ_INV": "CZ",
                        "X_INV": "X", "Z_INV": "Z"}


class FoldedQubitCode:
    """d = 2 templates mirroring ``FoldedQutritDetectionCode`` gate for gate.

    Wires 0-4 are data, 5 and 6 measure ``Z0 Z1 Z3`` and ``Z1 Z2 Z4``, 7 and 8
    measure ``X0 X1 X2`` and ``X1 X3 X4``. Each method is the qutrit method of
    the same name with qutrit inverse gates replaced by their d = 2 values;
    ``selftest`` checks this against the qutrit templates mechanically.
    """

    dimension = 2
    num_qudits = 9
    GATE_INVERSE = {"I": "I", "X": "X", "Z": "Z", "H": "H", "P": "P_INV",
                    "P_INV": "P", "CNOT": "CNOT", "CZ": "CZ", "SWAP": "SWAP"}

    @classmethod
    def _circuit(cls) -> Circuit:
        return Circuit(dimension=cls.dimension, num_qudits=cls.num_qudits)

    @classmethod
    def logical_plus_initial_state(cls) -> Circuit:
        c = cls._circuit()
        c.add_gate("H", [2, 3, 4])           # qutrit: H_INV
        c.add_gate("CNOT", 2, 1)             # qutrit: CNOT_INV
        c.add_gate("CNOT", 1, 0)
        c.add_gate("CNOT", 3, 0)
        c.add_gate("CNOT", 4, 2)
        return c

    @classmethod
    def elementary_sequence(cls, token: str):
        """(gates, controls, targets) of one logical token, qutrit layout."""
        base = token[0]
        if base == "I":
            gates, controls, targets = ["I"], [0], [None]
        elif base == "X":
            gates, controls, targets = ["X"], [[0, 3]], [None]
        elif base == "Z":
            gates, controls, targets = ["Z"], [[0, 2]], [None]
        elif base == "H":
            # qutrit: SWAP(2,3), H on 0,2,3,4, H_INV on 1
            gates = ["SWAP", "H", "H"]
            controls = [2, [0, 2, 3, 4], 1]
            targets = [3, None, None]
        elif base == "P":
            gates = ["P", "P_INV", "CZ"]
            controls = [[0, 4], 1, 2]
            targets = [None, None, 3]
        else:
            raise ValueError(f"Unsupported logical token {token!r}.")
        if len(token) > 1:
            if token[1:] != "_INV":
                raise ValueError(f"Unsupported logical token {token!r}.")
            gates = [cls.GATE_INVERSE[g] for g in reversed(gates)]
            controls = list(reversed(controls))
            targets = list(reversed(targets))
        return gates, controls, targets

    @classmethod
    def single_qudit_logical_gate_circuit(cls, token: str) -> Circuit:
        c = cls._circuit()
        for gate, control, target in zip(*cls.elementary_sequence(token)):
            if target is None:
                c.add_gate(gate, control)
            else:
                c.add_gate(gate, control, target)
        return c

    @classmethod
    def z_ALT_stabilizer_measurement_ancillae_circuit(cls) -> Circuit:
        c = cls._circuit()
        c.add_gate("CNOT", 0, 5)
        c.add_gate("CNOT", 1, 5)             # qutrit: CNOT_INV
        c.add_gate("CNOT", 3, 5)             # qutrit: CNOT_INV
        c.add_gate("M", 5)
        c.add_gate("CNOT", 1, 6)
        c.add_gate("CNOT", 2, 6)
        c.add_gate("CNOT", 4, 6)             # qutrit: CNOT_INV
        c.add_gate("M", 6)
        return c

    @classmethod
    def x_stabilizer_measurement_ancillae_circuit(cls) -> Circuit:
        c = cls._circuit()
        c.add_gate("H", 7)
        c.add_gate("CNOT", 7, 0)
        c.add_gate("CNOT", 7, 1)
        c.add_gate("CNOT", 7, 2)             # qutrit: CNOT_INV
        c.add_gate("H", 7)                   # qutrit: H_INV
        c.add_gate("M", 7)
        c.add_gate("H", 8)
        c.add_gate("CNOT", 8, 3)
        c.add_gate("CNOT", 8, 1)             # qutrit: CNOT_INV
        c.add_gate("CNOT", 8, 4)             # qutrit: CNOT_INV
        c.add_gate("H", 8)                   # qutrit: H_INV
        c.add_gate("M", 8)
        return c

    @classmethod
    def reset_measurement_wires(cls) -> Circuit:
        c = cls._circuit()
        for wire in ANCILLAS:
            c.add_gate("RESET", wire)
        return c

    @classmethod
    def terminal_logical_x_measurement_circuit(cls) -> Circuit:
        c = cls._circuit()
        c.add_gate("H", [0, 3])              # qutrit: H_INV
        c.add_gate("M", [0, 3])
        return c

    @classmethod
    def terminal_const0_logical_x_measurement_circuit(cls) -> Circuit:
        c = cls._circuit()
        c.add_gate("H", [0, 1, 2, 3, 4])     # qutrit: H_INV
        c.add_gate("M", [0, 1, 2, 3, 4])
        return c

    @staticmethod
    def affected_wires_per_operator(operator: str) -> list[int]:
        if operator in ("H", "H_INV", "P", "P_INV"):
            return [0, 1, 2, 3, 4]
        if operator in ("X", "X_INV"):
            return [0, 3]
        if operator in ("Z", "Z_INV"):
            return [0, 2]
        if operator == "I":
            return []
        raise ValueError(f"Unsupported logical token {operator!r}.")

    @classmethod
    def affected_wires(cls, cliff: Iterable[str]) -> list[int]:
        wires: set[int] = set()
        for gate in cliff:
            wires.update(cls.affected_wires_per_operator(gate))
        return sorted(wires)

    @staticmethod
    def codespace_X_stabilizer_check(x: Sequence[int]) -> bool:
        """``X0 X1 X2`` and ``X1 X3 X4`` from direct X-basis data outcomes."""
        return ((x[0] + x[1] + x[2]) % 2 == 0
                and (x[3] + x[1] + x[4]) % 2 == 0)


