def sequences() -> list[list[str]]:
    return QE.clifford_sequences(NUM_SEQ, SEQ_LENGTH, SEQ_SEED)


def sdim_circuits(sequence: Sequence[str], depths: Sequence[int], p: float,
                  kind: str) -> dict[int, Circuit]:
    """Repo-generated SI1000 circuits, one per depth, with noise set to ``p``.

    ``clifford_strings`` is cut to exactly ``max(depths)`` descriptors.
    ``generate_lrb_clifford_sequence`` slices the reversed inverse list at
    ``max_depth - depth``, which is only right when the list has exactly
    ``max_depth`` entries (``generate_tests`` always passes that many).
    """
    generator = LRBCircuitGenerator(code_definition=PROFILE.code_definition,
                                    noise_model="si1000")
    depths = sorted(depths)
    strings = list(sequence[:depths[-1]])
    if kind == "lrb":
        circuits = generator.generate_lrb_clifford_sequence(
            depths=depths, with_noise=True, clifford_strings=strings)
    elif kind == "const0":
        circuits = generator.generate_lrb_const0_clifford_sequence(
            depths=depths, with_noise=True, clifford_strings=strings)
    else:
        raise ValueError(kind)
    for circuit in circuits:
        generator.update_noise_param(circuit, p)
        NoiseModelUtils.ensure_noise_params(circuit)
    return dict(zip(depths, circuits))


def sdim_frame_sample(circuit: Circuit, extra_shots: int, seed: int):
    """sdim Pauli-frame sampling with one noiseless reference shot.

    Same calls, in the same order, as ``Program.simulate(shots=extra + 1)`` in
    sdim 1.4.0, without the step that wraps every frame shot in a Python
    object: a noiseless tableau reference shot, then the frame run, which
    draws the noise gate by gate. Returns ``((reference_results,
    detector_payload), frame)`` where the first element has the shape
    ``Program.simulate`` returns to the repo's detector-backed unpackers.
    """
    np.random.seed(seed % (2 ** 32))
    random.seed(seed)
    program = Program(circuit)
    program._tableau_noise_enabled = False
    try:
        program._simulate_tableau(SimulationOptions(shots=1))
    finally:
        program._tableau_noise_enabled = True
    reference = program.measurement_results
    reference_array = program._results_to_array(reference)
    tableau = program.stabilizer_tableau
    ir_array, noise, info, noise_model = program._build_ir(
        program.circuits, extra_shots, sample_noise=False,
        num_qudits=tableau.num_qudits)
    frame, events = simulate_frame(ir_array, reference_array,
                                   tableau.num_qudits, tableau.dimension,
                                   extra_shots, noise, info, noise_model)
    payload = program._combine_detector_results(info, events)
    return (reference, payload), frame


# ---------------------------------------------------------------------------
# 3. Per-shot data in a common format
# ---------------------------------------------------------------------------
#
# For both simulators a chunk of shots is reduced to:
#   raw     (shots, rounds, nstab) bool: stabilizer outcome != noiseless value
#   diff    (shots, rounds, nstab) bool: difference detection events
#   logical (shots,) bool: logical X readout flipped
#   accept  {policy: (shots,) bool}
# ``lrb`` circuits have rounds = depth + 1 and nstab = 4; ``const0`` circuits
# have one terminal "round" with the two direct X-stabilizer parities.

def raw_to_diff(raw: np.ndarray, lc: Q.LRBCircuit) -> np.ndarray:
    """Difference detectors from raw flips with the lead's ``back`` subsets."""
    diff = raw.copy()
    for k in range(1, raw.shape[1]):
        label = lc.rounds[k]
        for s in range(raw.shape[2]):
            for prev_s in lc.back[label][s]:
                diff[:, k, s] ^= raw[:, k - 1, prev_s]
    return diff


def lead_circuit(kind: str, sequence: Sequence[str], depth: int,
                 p: float) -> Q.LRBCircuit:
    if kind == "lrb":
        return Q.build_lrb_circuit(sequence, depth, p, terminal="data2")
    return Q.build_lrb_const0_circuit(sequence, depth, p)


def process_sdim(kind: str, output, frame: np.ndarray, depth: int,
                 extra_shots: int, lc: Q.LRBCircuit) -> dict:
    """Run the repo's unpack/postselection path and cross-check it."""
    reference, _ = output
    shots = extra_shots + 1
    compact = LRBSimulationPipeline.compact_detector_results_from_sdim_output(
        output)
    if kind == "lrb":
        checks, logical = PROFILE.unpack_func(output, depth, shots)
        policies = (("const", 1), ("unif", 1))
    else:
        checks, logical = PROFILE.const0_unpack_func(output, depth, shots)
        policies = (("const", 0),)
    # LRBSimulationPipeline.LRB drops shot 0, the noiseless reference shot.
    checks = np.asarray(checks, dtype=np.int64)[1:]
    logical = np.asarray(logical, dtype=np.int64)[1:]
    record = np.zeros((1, 1, extra_shots, depth + 1), dtype=np.int64)
    record[0, 0, :, :checks.shape[1]] = checks
    measurement_record = logical[None, None, :]

    accept: dict[str, np.ndarray] = {}
    repo_counts: dict[str, tuple[int, int, int]] = {}
    for policy, k in policies:
        if policy == "const":
            decision = LRBSimulationPipeline.postselect_constant_number(
                record, [depth], k)
        else:
            decision = LRBSimulationPipeline.postselect_uniform_interval(
                record, [depth], k)
        post = LRBSimulationPipeline.postselect_record(measurement_record,
                                                       decision)
        counts, rejected = LRBSimulationPipeline.extract_lrb_counts(
            post, dimension=2)
        name = f"{policy}{k}"
        accept[name] = decision[0, 0].astype(bool)
        repo_counts[name] = (int(counts[0, 0, 0]), int(counts[0, 0, 1]),
                             int(rejected[0, 0]))

    # Absolute stabilizer values (reference + shift), as the repo postselects.
    if kind == "lrb":
        raw = np.zeros((extra_shots, depth + 1, 4), dtype=bool)
        ref_values = []
        for r in range(depth + 1):
            for s, wire in enumerate(ANCILLAS):
                ref = int(reference[wire][2 * r][0].measurement_value)
                ref_values.append(ref)
                shift = compact["detectors"][f"lrb_stab_r{r}_w{wire}"]
                raw[:, r, s] = (ref + shift) % 2 != 0
                # The legacy raw-measurement path must agree: frame values of
                # the ancilla measurement (stride 2 = M then RESET slot).
                assert np.array_equal(
                    frame["measurement_value"][wire, 2 * r] % 2 != 0,
                    raw[:, r, s]), (r, wire)
        logical_ref = sum(int(reference[w][0][0].measurement_value)
                          for w in (0, 3)) % 2
        assert np.array_equal(
            (frame["measurement_value"][0, 0]
             + frame["measurement_value"][3, 0]) % 2, logical)
        diff = raw_to_diff(raw, lc)
    else:
        raw = np.zeros((extra_shots, 1, 2), dtype=bool)
        ref_values = []
        for i, terms in enumerate(QUBIT_TERMINAL_X_TERMS):
            ref = sum(int(reference[w][0][0].measurement_value) * c
                      for w, c in terms) % 2
            ref_values.append(ref)
            shift = compact["detectors"][f"lrb_const0_xstab_{i}"]
            raw[:, 0, i] = (ref + shift) % 2 != 0
            values = sum(frame["measurement_value"][w, 0] * c
                         for w, c in terms) % 2
            assert np.array_equal(values != 0, raw[:, 0, i]), i
        logical_ref = sum(int(reference[w][0][0].measurement_value)
                          for w in (0, 3)) % 2
        diff = raw.copy()
    # The repo's unpacker must agree with the raw detector arrays.
    for r in range(checks.shape[1]):
        if kind == "lrb" or r == depth:
            column = raw[:, r if kind == "lrb" else 0, :]
            assert np.array_equal(checks[:, r] == 1, ~column.any(axis=1)), r
    for name, (zeros, ones, rejected) in repo_counts.items():
        acc = accept[name]
        assert zeros + ones + rejected == extra_shots
        assert ones == int((logical[acc] != 0).sum())
        assert rejected == int((~acc).sum())
    return {"raw": raw, "diff": diff, "logical": logical != 0,
            "accept": accept, "ref_values": ref_values,
            "logical_ref": logical_ref}


def stim_chunk(kind: str, lc: Q.LRBCircuit, depth: int, shots: int,
               seed: int) -> dict:
    sampler = lc.circuit.compile_detector_sampler(seed=seed)
    dets, obs = sampler.sample(shots, separate_observables=True)
    logical = obs[:, 0]
    if kind == "lrb":
        raw = lc.raw_syndromes(dets)
        diff = dets[:, :4 * lc.num_rounds].reshape(shots, lc.num_rounds, 4)
        assert np.array_equal(raw_to_diff(raw, lc), diff)
        accept = {
            "const1": B.accept_mask(raw, lc.rounds,
                                    B.used_rounds("const", 1, depth)),
            "unif1": B.accept_mask(raw, lc.rounds,
                                   B.used_rounds("unif", 1, depth)),
        }
    else:
        raw = dets.reshape(shots, 1, 2)
        diff = raw.copy()
        accept = {"const0": ~dets.any(axis=1)}
    return {"raw": raw, "diff": diff, "logical": logical, "accept": accept}


def summarize(kind: str, data: dict) -> dict:
    """Reduce per-shot data of one chunk to additive counts."""
    raw, diff, logical = data["raw"], data["diff"], data["logical"]
    n = raw.shape[0]
    out = {"n": n, "flip_all": int(logical.sum())}
    for name, acc in data["accept"].items():
        out[f"rej_{name}"] = int((~acc).sum())
        out[f"acc_{name}"] = int(acc.sum())
        out[f"flip_{name}"] = int((acc & logical).sum())
    out["raw"] = raw.sum(axis=0).astype(np.int64)
    out["diff"] = diff.sum(axis=0).astype(np.int64)
    # Joint table 1: last-round raw pattern x logical bit.
    last = raw[:, -1, :]
    nstab = last.shape[1]
    index = (last.astype(np.int64) @ (1 << np.arange(nstab))
             + (logical.astype(np.int64) << nstab))
    out["hist_term"] = np.bincount(index, minlength=1 << (nstab + 1))
    # Joint table 2: number of detection events x logical bit.
    weight = diff.reshape(n, -1).sum(axis=1).astype(np.int64)
    width = diff.shape[1] * diff.shape[2] + 1
    out["hist_weight"] = np.bincount(weight + width * logical.astype(np.int64),
                                     minlength=2 * width)
    return out


def add_counts(total: dict | None, part: dict) -> dict:
    if total is None:
        return {k: (v.copy() if isinstance(v, np.ndarray) else v)
                for k, v in part.items()}
    for key, value in part.items():
        total[key] = total[key] + value
    return total


