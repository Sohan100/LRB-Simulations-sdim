def fmt_unc(value: float, se: float) -> str:
    """``0.27412(63)`` style: value with the SE in units of the last digit."""
    if math.isnan(value):
        return "n/a"
    if se <= 0 or math.isnan(se):
        return f"{value:.4g}"
    digits = max(0, -int(math.floor(math.log10(se))) + 1)
    scaled = int(round(se * 10 ** digits))
    return f"{value:.{digits}f}({scaled})"


def _table_cell(t: dict, sim: str) -> str:
    k, n = int(t[f"{sim}_k"]), int(t[f"{sim}_n"])
    if n == 0:
        return "no acc."
    rate, se = float(t[f"rate_{sim}"]), float(t[f"se_{sim}"])
    if se == 0 or k < 10 or n - k < 10:
        return f"{k}/{n}"
    return fmt_unc(rate, se)


def cmd_table(args) -> None:
    """Markdown tables of the headline comparisons (exact, sdim, Stim, z)."""
    out = Path(args.out)
    tests = read_csv(out / "tests_headline.csv")
    index = {(t["kind"], int(t["seq"]), int(t["depth"]), float(t["p"]),
              t["quantity"]): t for t in tests}
    labels = {"rej_const1": "rej const=1", "rej_unif1": "rej unif=1",
              "flip_const1|acc": "flip const=1", "flip_unif1|acc":
              "flip unif=1", "rej_const0": "rej const=0",
              "flip_const0|acc": "flip const=0"}
    specs = (("LRB data2 circuits: rejection", "lrb",
              ("rej_const1", "rej_unif1")),
             ("LRB data2 circuits: logical flip rate among accepted shots",
              "lrb", ("flip_const1|acc", "flip_unif1|acc")),
             ("const=0 circuits: rejection and flip rate among accepted",
              "const0", ("rej_const0", "flip_const0|acc")))
    for title, kind, quantities in specs:
        circuits = sorted({k[1:4] for k in index if k[0] == kind},
                          key=lambda c: (c[2], c[1], c[0]))
        print(f"**{title}**\n")
        header = ["p", "seq", "m"]
        for q in quantities:
            header += [f"{labels[q]} exact", "sdim", "Stim", "z"]
        print("| " + " | ".join(header) + " |")
        print("|" + "---|" * len(header))
        for s, d, p in circuits:
            cells = [f"{p:g}", str(s), str(d)]
            for q in quantities:
                t = index[(kind, s, d, p, q)]
                exact = float(t["exact"])
                z = float(t["z"])
                cells += ["-" if math.isnan(exact) else f"{exact:.5g}",
                          _table_cell(t, "sdim"), _table_cell(t, "stim"),
                          "n/a" if math.isnan(z) else f"{z:+.2f}"]
            print("| " + " | ".join(cells) + " |")
        print()


