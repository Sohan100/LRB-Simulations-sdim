_REC = re.compile(r"([+-]?)\s*(?:(\d+)\s*\*\s*)?rec\[(-?\d+)\]")


def n2_depolarizing_probability(params: dict) -> float:
    """The DEPOLARIZE2 strength of a d = 2 N2 gate (``prob``, or ``prob_dist``)."""
    if "prob_dist" not in params:
        return float(params["prob"])
    dist = np.asarray(params["prob_dist"], dtype=float)
    prob = 1.0 - dist[0]
    if not np.allclose(dist[1:], prob / 15, rtol=1e-12, atol=0):
        raise ValueError("N2 distribution is not uniform depolarizing.")
    return float(prob)


def sdim_to_stim(circuit: Circuit) -> stim.Circuit:
    """Translate a d = 2 sdim circuit into an equivalent Stim circuit.

    Gates map one to one (P -> S, P_INV -> S_DAG, CNOT -> CX, RESET -> R).
    N1 channels map to DEPOLARIZE1 ('d'), X_ERROR ('f') or Z_ERROR ('p').
    N2 maps to DEPOLARIZE2: the generator leaves only ``prob`` on it, which
    sdim 1.4.0 reads as uniform two-qubit depolarizing; an explicit
    ``prob_dist`` must be that uniform 15-Pauli law.
    DETECTOR / LOGICAL_OBSERVABLE expressions are parsed (mod 2).
    """
    if circuit.dimension != 2:
        raise ValueError("Only d = 2 circuits can be translated.")
    one = {"I": "I", "X": "X", "X_INV": "X", "Z": "Z", "Z_INV": "Z",
           "H": "H", "H_INV": "H", "P": "S", "P_INV": "S_DAG", "M": "M",
           "RESET": "R"}
    two = {"CNOT": "CX", "CNOT_INV": "CX", "CZ": "CZ", "CZ_INV": "CZ",
           "SWAP": "SWAP"}
    out = stim.Circuit()
    measurements = 0
    for op in circuit.operations:
        name = op.name
        if name in one:
            out.append(one[name], [op.qudit_index])
            if name == "M":
                measurements += 1
        elif name in two:
            out.append(two[name], [op.qudit_index, op.target_index])
        elif name == "N1":
            channel = op.params["noise_channel"]
            prob = float(op.params["prob"])
            gate = {"d": "DEPOLARIZE1", "f": "X_ERROR",
                    "p": "Z_ERROR"}[channel]
            if prob > 0:
                out.append(gate, [op.qudit_index], prob)
        elif name == "N2":
            prob = n2_depolarizing_probability(op.params)
            if prob > 0:
                out.append("DEPOLARIZE2", [op.qudit_index, op.target_index],
                           prob)
        elif name in ("DETECTOR", "LOGICAL_OBSERVABLE"):
            parity: dict[int, int] = {}
            for sign, coefficient, index in _REC.findall(op.params["expr"]):
                index = int(index) % measurements
                value = int(coefficient or 1)
                parity[index] = (parity.get(index, 0) + value) % 2
            targets = [stim.target_rec(i - measurements)
                       for i, v in sorted(parity.items()) if v]
            if name == "DETECTOR":
                out.append("DETECTOR", targets)
            else:
                out.append("OBSERVABLE_INCLUDE", targets, 0)
        elif name == "TICK":
            continue
        else:
            raise ValueError(f"Untranslatable sdim gate {name}.")
    return out


def lead_raw_circuit(kind: str, lc: Q.LRBCircuit) -> stim.Circuit:
    """The lead's circuit with raw (single-measurement) detectors.

    Detector order matches the repo generator: (round, ancilla 5..8) for LRB
    circuits; the two direct X parities for ``const0``.
    """
    out = stim.Circuit()
    records: dict[int, list[int]] = {}
    count = 0
    for inst in lc.circuit.flattened():
        if inst.name in ("DETECTOR", "OBSERVABLE_INCLUDE"):
            continue
        out.append(inst)
        if inst.name == "M":
            for target in inst.targets_copy():
                records.setdefault(target.value, []).append(count)
                count += 1
    total = out.num_measurements

    def rec(indices):
        return [stim.target_rec(i - total) for i in indices]

    if kind == "lrb":
        for r in range(lc.num_rounds):
            for wire in ANCILLAS:
                out.append("DETECTOR", rec([records[wire][r]]))
    else:
        for terms in QUBIT_TERMINAL_X_TERMS:
            out.append("DETECTOR", rec([records[w][-1] for w, _ in terms]))
    out.append("OBSERVABLE_INCLUDE", rec([records[0][-1], records[3][-1]]), 0)
    return out


def dem_mechanisms(dem: stim.DetectorErrorModel) -> dict:
    """{(detectors, observables): probability}, merging equal symptoms."""
    mechanisms: dict = {}
    for inst in dem.flattened():
        if inst.type != "error":
            continue
        prob = inst.args_copy()[0]
        dets, obs = [], []
        for target in inst.targets_copy():
            if target.is_relative_detector_id():
                dets.append(target.val)
            elif target.is_logical_observable_id():
                obs.append(target.val)
        key = (frozenset(dets), frozenset(obs))
        old = mechanisms.get(key, 0.0)
        mechanisms[key] = old * (1 - prob) + prob * (1 - old)
    return mechanisms


def compare_dems(kind: str, sequence: Sequence[str], depth: int, p: float,
                 sdim_circuit: Circuit | None = None,
                 lead_sequence: Sequence[str] | None = None,
                 lead_noise: Q.SI1000 | None = None) -> dict:
    """Compare the sdim circuit's DEM with the lead circuit's DEM.

    ``lead_sequence`` and ``lead_noise`` are only used by negative controls.
    """
    if sdim_circuit is None:
        sdim_circuit = sdim_circuits(sequence, [depth], p, kind)[depth]
    translated = sdim_to_stim(sdim_circuit)
    lead_sequence = sequence if lead_sequence is None else lead_sequence
    if lead_noise is None:
        lc = lead_circuit(kind, lead_sequence, depth, p)
    elif kind == "lrb":
        lc = Q.build_lrb_circuit(lead_sequence, depth, p, terminal="data2",
                                 noise=lead_noise)
    else:
        lc = Q.build_lrb_const0_circuit(lead_sequence, depth, p,
                                        noise=lead_noise)
    lead = lead_raw_circuit(kind, lc)
    m_sdim = dem_mechanisms(translated.detector_error_model())
    m_lead = dem_mechanisms(lead.detector_error_model())
    keys = set(m_sdim) | set(m_lead)
    diffs = [abs(m_sdim.get(k, 0.0) - m_lead.get(k, 0.0)) for k in keys]
    # Symmetric relative difference; 1.0 when a mechanism is missing.
    rel = [abs(m_sdim.get(k, 0.0) - m_lead.get(k, 0.0))
           / max(m_sdim.get(k, 0.0), m_lead.get(k, 0.0), 1e-300)
           for k in keys]
    silent = (frozenset(), frozenset({0}))
    return {
        "kind": kind, "depth": depth, "p": p,
        "num_detectors_sdim": translated.num_detectors,
        "num_detectors_lead": lead.num_detectors,
        "mechanisms_sdim": len(m_sdim), "mechanisms_lead": len(m_lead),
        "same_symptom_sets": set(m_sdim) == set(m_lead),
        "max_abs_prob_diff": max(diffs) if diffs else 0.0,
        "max_rel_prob_diff": max(rel) if rel else 0.0,
        "total_prob_sdim": sum(m_sdim.values()),
        "total_prob_lead": sum(m_lead.values()),
        # Faults that flip the logical readout and fire no detector.
        "undetectable_logical_sdim": m_sdim.get(silent, 0.0),
        "undetectable_logical_lead": m_lead.get(silent, 0.0),
        "identical": (set(m_sdim) == set(m_lead)
                      and (max(rel) if rel else 0.0) < 1e-9),
    }


def _fire_probabilities(mechanisms: dict, num_detectors: int) -> tuple:
    """Exact P(detector fires) and P(observable 0 flips) from a DEM."""
    det_bias = np.ones(num_detectors)
    obs_bias = 1.0
    for (dets, obs), prob in mechanisms.items():
        for d in dets:
            det_bias[d] *= 1 - 2 * prob
        if 0 in obs:
            obs_bias *= 1 - 2 * prob
    return (1 - det_bias) / 2, (1 - obs_bias) / 2


def exact_marginals(kind: str, sequence: Sequence[str], depth: int,
                    p: float) -> dict[str, float]:
    """Exact per-detector and logical marginals of the lead's circuit."""
    lc = lead_circuit(kind, sequence, depth, p)
    out: dict[str, float] = {}
    raw_circuit = lead_raw_circuit(kind, lc)
    det, obs = _fire_probabilities(
        dem_mechanisms(raw_circuit.detector_error_model()),
        raw_circuit.num_detectors)
    out["flip_all"] = float(obs)
    if kind == "lrb":
        for i, value in enumerate(det):
            out[f"raw_r{i // 4}_s{i % 4}"] = float(value)
        det_d, _ = _fire_probabilities(
            dem_mechanisms(lc.circuit.detector_error_model()),
            lc.circuit.num_detectors)
        for i, (label, s) in enumerate(lc.detector_keys):
            out[f"diff_r{lc.rounds.index(label)}_s{s}"] = float(det_d[i])
    else:
        for i, value in enumerate(det):
            out[f"xstab_{i}"] = float(value)
    return out


def _exact_joint(mechanisms: dict, bits: Sequence[tuple[str, int]]
                 ) -> np.ndarray:
    """Exact distribution of selected detector/observable bits.

    ``bits`` lists ("d", detector) or ("o", observable); the result is a
    vector over the 2**len(bits) bit patterns (bit j = bits[j]).
    """
    size = 1 << len(bits)
    states = np.arange(size)
    dist = np.zeros(size)
    dist[0] = 1.0
    for (dets, obs), prob in mechanisms.items():
        mask = 0
        for j, (kind, index) in enumerate(bits):
            if (index in dets) if kind == "d" else (index in obs):
                mask |= 1 << j
        if mask:
            dist = (1 - prob) * dist + prob * dist[states ^ mask]
    return dist


def exact_headline(kind: str, sequence: Sequence[str], depth: int,
                   p: float) -> dict[str, float]:
    """Exact rejection and flip-among-accepted values where tractable.

    const=1 and const=0 need only 5 and 3 bits. unif=1 needs every detector,
    so it is computed only up to depth 2 (13 bits).
    """
    lc = lead_circuit(kind, sequence, depth, p)
    circuit = lead_raw_circuit(kind, lc)
    mechanisms = dem_mechanisms(circuit.detector_error_model())
    out: dict[str, float] = {}
    if kind == "lrb":
        policies = [("const1", [4 * depth + s for s in range(4)])]
        if depth <= 2:
            policies.append(("unif1", list(range(4 * (depth + 1)))))
    else:
        policies = [("const0", [0, 1])]
    for name, dets in policies:
        bits = [("d", d) for d in dets] + [("o", 0)]
        dist = _exact_joint(mechanisms, bits)
        accept = dist[0] + dist[1 << len(dets)]
        out[f"rej_{name}"] = 1.0 - accept
        out[f"flip_{name}|acc"] = (dist[1 << len(dets)] / accept
                                   if accept > 0 else math.nan)
    return out


