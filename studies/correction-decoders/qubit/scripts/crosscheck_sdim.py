def _ops(circuit: Circuit) -> list[tuple]:
    return [(op.name, op.qudit_index, op.target_index)
            for op in circuit.operations]


def _translate_qutrit(circuit: Circuit) -> list[tuple]:
    return [(QUTRIT_TO_QUBIT_NAME.get(op.name, op.name), op.qudit_index,
             op.target_index) for op in circuit.operations]


def _single_shot(circuit: Circuit) -> list:
    random.seed(0)
    np.random.seed(0)
    return Program(circuit).simulate(shots=1)


def _random_clifford_check(trials: int, rng: np.random.Generator) -> int:
    """sdim (d = 2) tableau vs Stim on random Clifford circuits.

    Every Z measurement must agree on determinism and, when deterministic, on
    the value. Random outcomes are forced in Stim to sdim's value.
    """
    names = ["H", "P", "P_INV", "X", "Z", "CNOT", "CZ", "SWAP"]
    stim_name = {"H": "H", "P": "S", "P_INV": "S_DAG", "X": "X", "Z": "Z",
                 "CNOT": "CX", "CZ": "CZ", "SWAP": "SWAP"}
    n = 4
    mismatches = 0
    for _ in range(trials):
        c = Circuit(dimension=2, num_qudits=n)
        sim = stim.TableauSimulator()
        sim.set_num_qubits(n)
        for _ in range(25):
            g = names[rng.integers(len(names))]
            if g in ("CNOT", "CZ", "SWAP"):
                a, b = rng.choice(n, size=2, replace=False)
                c.add_gate(g, int(a), int(b))
                sim.do(stim.Circuit(f"{stim_name[g]} {a} {b}"))
            else:
                q = int(rng.integers(n))
                c.add_gate(g, q)
                sim.do(stim.Circuit(f"{stim_name[g]} {q}"))
        for q in range(n):
            c.add_gate("M", q)
        results = _single_shot(c)
        for q, result in enumerate(results):
            peek = sim.peek_z(q)
            if peek == 0:
                if result.deterministic:
                    mismatches += 1
                sim.postselect_z(q, desired_value=bool(
                    result.measurement_value))
            else:
                expected = 1 if peek == -1 else 0
                if (not result.deterministic
                        or result.measurement_value != expected):
                    mismatches += 1
                sim.measure(q)
    return mismatches


def cmd_selftest(args) -> None:
    from sdim.circuit_io import cirq_statevector_from_circuit
    from sdim.unitary import generate_p_matrix

    rows = []

    def record(check: str, ok: bool, detail: str) -> None:
        rows.append({"check": check, "result": "PASS" if ok else "FAIL",
                     "detail": detail})
        print(f"[{'PASS' if ok else 'FAIL'}] {check}: {detail}", flush=True)

    # (a) d = 2 templates == qutrit templates with inverse names mapped.
    F, T = FoldedQubitCode, qutrit_defs.FoldedQutritDetectionCode
    pairs = [(F.logical_plus_initial_state, T.logical_plus_initial_state),
             (F.z_ALT_stabilizer_measurement_ancillae_circuit,
              T.z_ALT_stabilizer_measurement_ancillae_circuit),
             (F.x_stabilizer_measurement_ancillae_circuit,
              T.x_stabilizer_measurement_ancillae_circuit),
             (F.reset_measurement_wires, T.reset_measurement_wires),
             (F.terminal_logical_x_measurement_circuit,
              T.terminal_logical_x_measurement_circuit),
             (F.terminal_const0_logical_x_measurement_circuit,
              T.terminal_const0_logical_x_measurement_circuit)]
    bad = [f.__name__ for f, t in pairs if _ops(f()) != _translate_qutrit(t())]
    for token in ("I", "X", "Z", "H", "P", "X_INV", "Z_INV", "H_INV",
                  "P_INV"):
        if (_ops(F.single_qudit_logical_gate_circuit(token))
                != _translate_qutrit(T.single_qudit_logical_gate_circuit(
                    token))):
            bad.append(token)
    record("templates_mirror_folded_qutrit", not bad,
           "encoder, z_ALT, X checks, reset, both terminal readouts and the "
           "9 logical tokens equal the qutrit templates with H_INV->H, "
           "CNOT_INV->CNOT, CZ_INV->CZ, X_INV->X, Z_INV->Z"
           + (f"; mismatches: {bad}" if bad else ""))

    # (b) sdim's P at d = 2 is S = diag(1, i) (unitary and statevector).
    p_matrix = generate_p_matrix(2)
    ok_matrix = np.allclose(p_matrix, np.diag([1, 1j]))
    c = Circuit(dimension=2, num_qudits=1)
    c.add_gate("H", 0)
    c.add_gate("P", 0)
    psi = np.asarray(cirq_statevector_from_circuit(c))
    c_inv = Circuit(dimension=2, num_qudits=1)
    c_inv.add_gate("H", 0)
    c_inv.add_gate("P_INV", 0)
    psi_inv = np.asarray(cirq_statevector_from_circuit(c_inv))
    # cirq returns complex64 state vectors, hence the 1e-6 tolerance. The
    # two candidate states are orthogonal, so this separates S from S^dagger.
    ok_state = (abs(abs(np.vdot(psi, np.array([1, 1j]) / math.sqrt(2))) - 1)
                < 1e-6 and abs(abs(np.vdot(psi_inv, np.array([1, -1j])
                                          / math.sqrt(2))) - 1) < 1e-6)
    record("sdim_P_is_S_at_d2", ok_matrix and ok_state,
           f"generate_p_matrix(2)=diag{np.round(np.diag(p_matrix), 12)}; "
           "H then P on |0> gives (|0>+i|1>)/sqrt2, H then P_INV gives "
           "(|0>-i|1>)/sqrt2 (cirq statevector of the sdim circuit)")

    # (c) CNOT direction in sdim: add_gate("CNOT", a, b) has control a.
    outcomes = []
    for flip in (0, 1):
        c = Circuit(dimension=2, num_qudits=2)
        c.add_gate("X", flip)
        c.add_gate("CNOT", 0, 1)
        c.add_gate("M", [0, 1])
        outcomes.append(tuple(r.measurement_value for r in _single_shot(c)))
    record("sdim_CNOT_control_is_first_argument",
           outcomes == [(1, 1), (0, 1)],
           f"X0;CNOT 0 1 -> {outcomes[0]}, X1;CNOT 0 1 -> {outcomes[1]}")

    # (d) sdim d = 2 tableau agrees with Stim on random Clifford circuits.
    trials = 300
    mismatches = _random_clifford_check(trials, np.random.default_rng(5))
    record("sdim_d2_tableau_matches_stim_random_cliffords", mismatches == 0,
           f"{trials} random 4-qubit circuits (25 gates from H,P,P_INV,X,Z,"
           f"CNOT,CZ,SWAP), Z readout of all qubits: {mismatches} mismatches "
           "in determinism or deterministic value")

    # (e) Noiseless references: every descriptor, LRB and const0 circuits.
    failures = []
    for descriptor in QC.SINGLE_QUBIT_CLIFFORDS:
        for kind in ("lrb", "const0"):
            circuit = sdim_circuits([descriptor], [1], 0.0, kind)[1]
            output, frame = sdim_frame_sample(circuit, 64, 1)
            lc = lead_circuit(kind, [descriptor], 1, 0.0)
            data = process_sdim(kind, output, frame, 1, 64, lc)
            reference = output[0]
            deterministic = all(
                reference[w][m][0].deterministic
                for w in (ANCILLAS if kind == "lrb" else ())
                for m in range(len(reference[w])))
            if (any(data["ref_values"]) or data["logical_ref"]
                    or data["raw"].any() or data["logical"].any()
                    or not deterministic):
                failures.append((descriptor, kind))
    for s, sequence in enumerate(sequences()):
        for kind in ("lrb", "const0"):
            circuits = sdim_circuits(sequence, (0, 2, 6, 22), 0.0, kind)
            for depth, circuit in circuits.items():
                output, frame = sdim_frame_sample(circuit, 64, 2)
                lc = lead_circuit(kind, sequence, depth, 0.0)
                data = process_sdim(kind, output, frame, depth, 64, lc)
                if (any(data["ref_values"]) or data["logical_ref"]
                        or data["raw"].any() or data["logical"].any()):
                    failures.append((s, kind, depth))
    record("noiseless_sdim_circuits_trivial", not failures,
           "24 descriptors at depth 1 and 3 sequences at depths 0,2,6,22 "
           "(LRB and const0): reference ancilla values 0 and deterministic, "
           "reference logical x0+x3 = 0, no detection events or logical "
           "shifts in 64 noiseless frame shots"
           + (f"; failures {failures}" if failures else ""))

    # (f) Fast path == Program.simulate under the same seeds.
    sequence = sequences()[0]
    same = True
    for kind, depth in (("lrb", 2), ("const0", 6)):
        circuit = sdim_circuits(sequence, [depth], 0.02, kind)[depth]
        (reference, payload), frame = sdim_frame_sample(circuit, 400, 99)
        np.random.seed(99)
        random.seed(99)
        measurements, payload_full = Program(circuit).simulate(shots=401)
        for group in ("detectors", "logicals"):
            for x, y in zip(payload[group], payload_full[group]):
                same &= (x["label"] == y["label"]
                         and np.array_equal(x["data"], y["data"]))
        for w in range(9):
            for m in range(len(measurements[w])):
                values = [r.measurement_value for r in measurements[w][m]]
                same &= values[0] == reference[w][m][0].measurement_value
                same &= values[1:] == list(
                    frame["measurement_value"][w, m])
    record("fast_frame_path_equals_Program.simulate", bool(same),
           "detector/logical arrays, reference shot and every frame "
           "measurement identical to Program(circuit).simulate(shots=401) "
           "with the same numpy/random seeds (LRB depth 2 and const0 depth 6,"
           " p=0.02)")

    # (g) Noise parameters after the repo's preprocessing.
    circuit = sdim_circuits(sequence, [6], 0.02, "lrb")[6]
    n1 = {}
    n2_ok = True
    for op in circuit.operations:
        if op.name == "N1":
            key = (op.params["noise_channel"],
                   round(float(op.params["prob"]) / 0.02, 9))
            n1[key] = n1.get(key, 0) + 1
        elif op.name == "N2":
            n2_ok &= abs(n2_depolarizing_probability(op.params) - 0.02) < 1e-15
    record("sdim_noise_parameters_d2", n2_ok and set(n1) == {
        ("d", 0.1), ("d", 1.0), ("d", 2.0), ("f", 5.0), ("f", 2.0)},
        f"N1 (channel, prob/p) counts {sorted(n1.items())}; every N2 has "
        "strength p (DEPOLARIZE2(p)). sdim's 'd' channel "
        "draws X, Z, XZ uniformly (DEPOLARIZE1), 'f' draws X (X_ERROR)")

    # (h) Latent generator hazard: a pre-sampled list longer than max(depths).
    generator = LRBCircuitGenerator(code_definition=PROFILE.code_definition,
                                    noise_model="si1000")
    wrong = generator.generate_lrb_clifford_sequence(
        depths=[2], with_noise=True, clifford_strings=list(sequence[:6]))[0]
    right = generator.generate_lrb_clifford_sequence(
        depths=[2], with_noise=True, clifford_strings=list(sequence[:2]))[0]
    count_wrong = sum(1 for op in wrong.operations if op.name == "SWAP")
    count_right = sum(1 for op in right.operations if op.name == "SWAP")
    for c in (wrong,):
        generator.update_noise_param(c, 0.0)
        NoiseModelUtils.ensure_noise_params(c)
    output, frame = sdim_frame_sample(wrong, 2000, 3)
    shifts = output[1]["logicals"][0]["data"]
    record("generator_presampled_list_longer_than_max_depth",
           count_wrong != count_right,
           "INFO (not a production bug): generate_lrb_clifford_sequence("
           "depths=[2], clifford_strings=<6 descriptors>) appends all 6 "
           f"inverses (SWAP count {count_wrong} vs {count_right} with 2 "
           "descriptors); the noiseless logical readout then flips in "
           f"{shifts.mean():.3f} of shots. generate_tests always passes "
           "exactly max(depths) descriptors, so production runs are safe")

    # (i) Reuse hazard: the unpack specs default to dimension = 3.
    spec3 = dataclasses.replace(QUBIT_UNPACK_SPEC, dimension=3)
    circuit = sdim_circuits(sequence, [0], 0.0, "lrb")[0]
    found: dict = {}
    for seed in range(64):
        output, _ = sdim_frame_sample(circuit, 50, 1000 + seed)
